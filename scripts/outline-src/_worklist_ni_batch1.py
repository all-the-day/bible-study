def line_of(vol, bi, ci, idx):
    lines = VOLS[vol]["books"][bi]["chapters"][ci]["content"].split("\n")
    return lines[idx].strip()


def build():
    chapters = {}
    stats = collections.Counter()
    for key in sorted(EMPTY):
        v, b, c = key
        chapters[f"{v}:{b}:{c}"] = []
        stats["empty"] += 1
    for (v, b, c), entries in sorted(CUR.items()):
        out = []
        for e in entries:
            idx, lv = e[0], e[1]
            text = line_of(v, b, c, idx)
            if len(e) > 2 and e[2] == "P":
                parts = text.split("\u3000")
                label = parts[1] if len(parts) >= 3 else text
                prefix = parts[0] + "\u3000" + (parts[1] if len(parts) >= 3 else "")
                out.append({"p": prefix, "l": lv, "label": label})
                stats["prefix"] += 1
            else:
                out.append({"t": text, "l": lv})
                stats["exact"] += 1
        chapters[f"{v}:{b}:{c}"] = out
    doc = {"series": "ni", "note": "第一批：第一辑·灵修指微 + 十字架的道（55 章）", "chapters": chapters}
    return doc, stats


if __name__ == "__main__":
    import sys
    data, stats = build()
    dst = os.path.join(ROOT, "scripts", "outline-src", "ni.json")
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    # 守卫（CR 2026-11-02）：本工单只含第一批 55 章，整文件覆盖会抹掉批次 2+ 的策展成果。
    # 现有文件里出现本工单没有的章 → 拒绝写入；真要重建首批并丢弃其余章节请显式加 --force。
    if os.path.isfile(dst):
        with open(dst, encoding="utf-8") as f:
            existing = json.load(f)
        extra = set((existing.get("chapters") or {})) - set(data["chapters"])
        if extra and "--force" not in sys.argv:
            print(f"✗ 拒绝覆盖 {dst}：文件里已有 {len(extra)} 章不在本工单内（批次 2+ 的成果）。"
                  f"后续批次用 _draft_books.py；确实要重建首批并丢弃其余章节，加 --force。")
            sys.exit(1)
    with open(dst, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    n = sum(1 for v in data["chapters"].values() if v)
    print(f"[OK] {dst}：{len(data['chapters'])} 章入册（{n} 章有纲目），"
          f"精确匹配 {stats['exact']} 条 / 前缀匹配 {stats['prefix']} 条 / 显式空 {stats['empty']} 章")
