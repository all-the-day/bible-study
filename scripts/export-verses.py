def clean(marked):
    """剥离 {N} 注脚与 [x] 串珠标记，返回纯文本。"""
    s = re.sub(r'\{[^}]*\}', '', marked)
    s = re.sub(r'\[[^\]]*\]', '', s)
    return s.strip()


def main():
    with open(SRC, encoding='utf-8') as f:
        text = json.load(f)
    out = []
    seen = set()
    for ref in VERSES:
        if ref in seen:
            continue
        seen.add(ref)
        marked = text.get(ref)
        if not marked:
            continue
        plain = clean(marked)
        if plain:
            out.append({'ref': ref, 'text': plain})
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    print(f'{len(out)}/{len(VERSES)} 节写入 {OUT}')
    missing = [r for r in VERSES if r not in text]
    if missing:
        print('缺失引用（已跳过）:', ' '.join(missing))


if __name__ == '__main__':
    main()
